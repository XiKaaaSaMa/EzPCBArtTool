"""Fetch every operator's official English name from PRTS and cache it.

The card's 干员代号 line is set in the template's own ``Agency FB Negreta``,
which draws Latin letters and nothing else -- a Chinese name renders as two
empty boxes. The English name is therefore the *right* text for that line, and
it is what makes the template's typeface usable at all.

**Where the name comes from.** PRTS' operator grid carries ``data-zh`` and
``data-en`` on the same element, so the pairing is the wiki's own rather than
something inferred from the page titles. Verified against the roster: 431 of
463 names come back, and the ones that do not are the 卫戍协议 alternates and
the generic 预备干员 rows -- see the report this tool prints.

**Cached, not fetched at run time.** The interface has to draw a card with no
network, so the result lands in ``pcbart/operator_names_en.py`` as a plain dict
keyed by page name, exactly like ``badge_short_urls``. Re-run this when the
roster grows.

Usage::

    python tools/fetch_operator_names_en.py
"""

from __future__ import annotations

import argparse
import html
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pcbart.operator_names import latin_part  # noqa: E402
from pcbart.paths import badge_asset_dir  # noqa: E402

OUTPUT = ROOT / "pcbart" / "operator_names_en.py"

LIST_URL = "https://prts.wiki/w/%E5%B9%B2%E5%91%98%E4%B8%80%E8%A7%88"

#: PRTS rejects the default urllib agent; this is the same one the asset fetch
#: tool uses, so the site sees one identifiable local client.
USER_AGENT = (
    "PCBArtTool-prts-fetch/1.0 "
    "(local asset library for a personal PCB art tool; contact: project owner)"
)


def fetch_grid(url: str = LIST_URL) -> str:
    """The operator list's HTML."""
    request = urllib.request.Request(
        url, headers={"User-Agent": USER_AGENT, "Referer": "https://prts.wiki/"}
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8", "replace")


def parse_names(markup: str) -> dict[str, str]:
    """``{Chinese name: English name}`` from the grid's own attributes.

    ``data-zh`` and ``data-en`` may appear in either order on an element, so
    both arrangements are tried; the names are HTML-escaped in the page (``&#39;``
    in ``Wiš'adel``, for one), which :func:`html.unescape` puts back.
    """
    pairs: list[tuple[str, str]] = []
    pairs += re.findall(r'data-zh="([^"]+)"[^>]*?data-en="([^"]*)"', markup)
    pairs += [
        (zh, en)
        for en, zh in re.findall(
            r'data-en="([^"]*)"[^>]*?data-zh="([^"]+)"', markup
        )
    ]
    result: dict[str, str] = {}
    for zh, en in pairs:
        zh = html.unescape(zh).strip()
        en = html.unescape(en).strip()
        # A missing English name is stored as an empty attribute; keeping the
        # key with an empty value would make the caller think it has a name.
        if zh and en and zh not in result:
            result[zh] = en
    return result


def roster_names() -> list[str]:
    """Every display name the card can be built for, from the roster itself."""
    from pcbart import operators

    database = operators.database()
    if not database:
        raise SystemExit(
            f"找不到干员资料库：{operators.db_path()}\n"
            "先把素材库放好，或设置 PCBART_ASSET_ROOT。"
        )
    return [person.name for person in database.operators]


def write_module(names: dict[str, str], out: Path) -> None:
    """Write the mapping as a Python module, sorted for a readable diff."""
    lines = [
        '"""Generated by ``tools/fetch_operator_names_en.py`` -- do not edit.',
        "",
        "Official English names, keyed by the operator's Chinese display name.",
        "The 干员代号 line is set in the template's Latin-only typeface, so it",
        "needs these rather than the Chinese name.",
        "",
        "**Only names PRTS actually carries.** A name that is missing here has",
        "no published English form (the 卫戍协议 alternates, the generic",
        "预备干员 rows), and the card falls back to the Chinese name rather",
        "than inventing a transliteration.",
        '"""',
        "",
        "NAME_EN: dict[str, str] = {",
    ]
    for name in sorted(names):
        lines.append(f"    {name!r}: {names[name]!r},")
    lines.append("}")
    lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUTPUT)
    parser.add_argument("--url", default=LIST_URL)
    args = parser.parse_args(argv)

    print(f"抓取 {args.url}")
    try:
        markup = fetch_grid(args.url)
    except (urllib.error.URLError, OSError) as exc:
        print(f"抓取失败：{exc}", file=sys.stderr)
        return 1
    parsed = parse_names(markup)
    print(f"页面里解析出 {len(parsed)} 条中英配对")

    wanted = roster_names()
    found = {name: parsed[name] for name in wanted if parsed.get(name)}
    missing = [name for name in wanted if name not in found]
    write_module(found, args.out)
    print(f"写入 {args.out}")
    print(f"  覆盖 {len(found)}/{len(wanted)} 位")

    non_latin = [
        (name, english)
        for name, english in found.items()
        if not english.isascii()
    ]
    if non_latin:
        print(f"  ⚠ {len(non_latin)} 位英文名含非拉丁字符：")
        for name, english in non_latin:
            print(f"     {name} → {english}")
        print("     模板字体画不出这些字符，卡片会用覆盖它们的字体代替。")
    if missing:
        # Of those, the ones whose *display name* is already Latin need no
        # translation -- "Pith" and "Sharp" are what the game calls them. The
        # resolver takes the Latin run out of the name for those.
        latin = [name for name in missing if latin_part(name)]
        print(f"  ⚠ {len(missing)} 位 PRTS 没有英文名：")
        for name in missing:
            mark = "（名字本身就是英文，直接用）" if name in latin else "（回退中文）"
            print(f"     {name} {mark}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
