"""Create and cache the 通行证 QR short links.

The operator index contains percent-encoded PRTS URLs.  The shortener's backend
mangled raw Chinese characters in testing, so this tool always sends a fully
percent-encoded ``https://prts.wiki/w/...`` target and lets urlc.cn create the
five-character ``i8c.cn/xxxxx`` link.  The API is idempotent for the same long
URL, so rerunning the tool reuses the existing link instead of piling up
duplicates.

The cache is deliberately a JSON file, not module code: it is account-specific
and can be regenerated.  Run without ``--limit`` to fill the whole roster.
"""

from __future__ import annotations

import argparse
import json
import pprint
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pcbart import badge_codes, operators  # noqa: E402
from pcbart.short_url import UrlcClient, UrlcError, load_token  # noqa: E402

DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "out" / "badge_short_urls.json"


def _load_cache(path: Path) -> dict:
    if not path.exists():
        return {"version": 1, "entries": {}}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"缓存文件读取失败：{path}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("entries"), dict):
        raise SystemExit(f"缓存文件格式不对：{path}")
    return data


def _save_cache(path: Path, cache: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(
        json.dumps(cache, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    temp.replace(path)


def _write_module(path: Path, entries: dict) -> None:
    """Write the page-name to short-URL map used by the application."""
    mapping = {}
    for entry in entries.values():
        page = str(entry.get("page") or "").strip()
        short = str(entry.get("short") or "").strip()
        if page and short:
            mapping[page] = short
    path.parent.mkdir(parents=True, exist_ok=True)
    text = (
        '"""Generated by ``tools/shorten_badge_urls.py`` -- do not edit by hand.\n\n'
        "Account-specific urlc.cn short links for the 通行证 QR code.  The\n"
        "links are idempotent on the provider side; rerun the tool after the\n"
        "operator index changes.  This module is deliberately separate from\n"
        "the code: if the shortener account is ever replaced, regenerate it.\n"
        '"""\n\n'
        "SHORT_URLS = "
        + pprint.pformat(mapping, width=100, sort_dicts=True)
        + "\n"
    )
    path.write_text(text, encoding="utf-8")
    print(f"程序映射写入 {path}（{len(mapping)} 条）")


def _operator_rows(limit: int | None) -> list:
    db = operators.database()
    rows = []
    seen: set[str] = set()
    for operator in db.operators:
        page = (operator.page or operator.name or "").strip()
        if not page:
            continue
        target = badge_codes.prts_target_url(page)
        if target in seen:
            continue
        seen.add(target)
        rows.append(operator)
        if limit is not None and len(rows) >= limit:
            break
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--limit", type=int, default=None, help="only fill N missing rows")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--module",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "pcbart" / "badge_short_urls.py",
        help="generated Python mapping used by the application",
    )
    parser.add_argument("--delay", type=float, default=0.15, help="seconds between new links")
    parser.add_argument("--dry-run", action="store_true", help="list what would be created")
    args = parser.parse_args(argv)

    cache = _load_cache(args.output)
    entries = cache["entries"]
    rows = _operator_rows(args.limit)
    missing = []
    for operator in rows:
        page = (operator.page or operator.name or "").strip()
        target = badge_codes.prts_target_url(page)
        if target not in entries:
            missing.append((operator, page, target))

    print(f"干员行 {len(rows)}，已有短链 {len(entries)}，本次待补 {len(missing)}")
    if args.dry_run:
        for operator, page, target in missing[:20]:
            print(f"  {operator.name} -> {target}")
        if len(missing) > 20:
            print(f"  ... 还有 {len(missing) - 20} 条")
        return 0

    if not missing:
        print("没有需要新增的短链。")
        _write_module(args.module, entries)
        return 0

    client = UrlcClient(load_token())
    failures = []
    for index, (operator, page, target) in enumerate(missing, 1):
        try:
            short = client.add(target)
        except UrlcError as exc:
            failures.append((operator.name, str(exc)))
            print(f"[{index}/{len(missing)}] {operator.name} 失败：{exc}")
            continue
        entries[target] = {
            "page": page,
            "name": operator.name,
            "number": operator.number,
            "short": short,
        }
        _save_cache(args.output, cache)
        print(f"[{index}/{len(missing)}] {operator.name} -> {short}")
        if args.delay:
            time.sleep(max(0.0, args.delay))

    print(f"完成：新增 {len(missing) - len(failures)}，失败 {len(failures)}，缓存 {args.output}")
    if failures:
        for name, error in failures[:10]:
            print(f"  {name}: {error}")
        return 1

    _write_module(args.module, entries)
    versions: dict[int, int] = {}
    for entry in entries.values():
        qr = badge_codes.qr_for_short_url(str(entry["short"]))
        versions[qr.version] = versions.get(qr.version, 0) + 1
    print("短链二维码版本分布：" + "，".join(f"v{v}: {n}" for v, n in sorted(versions.items())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
