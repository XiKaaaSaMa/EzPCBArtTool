#: Fallback hue for a seed with no colour in it.
#:
#: Black, white and grey have a chroma of zero, so their hue is mathematically
#: undefined -- ``atan2(0, 0)`` returns 0, which would silently produce a *pink*
#: scheme from a black seed. That is a surprise, not a feature. Falling back to
#: the baseline purple keeps the promise the panel makes: the surfaces and text
#: still follow the seed's lightness, and the accent is a deliberate neutral-ish
#: purple rather than an accident of floating-point arithmetic.
_FALLBACK_HUE = 304.9


def _scheme_roles(seed: str, dark: bool) -> dict[str, str]:
    """The Material 3 baseline mapping, read off four tonal palettes."""
    red, green, blue = _hex_to_rgb(seed)
    _, seed_chroma, seed_hue = _rgb_to_lch((red, green, blue))
    if seed_chroma < 1.0:
        seed_hue = _FALLBACK_HUE

    # Material's chroma budgets per family. The seed sets the hue; the family
    # sets how loud it is allowed to be.
    primary_chroma = max(24.0, min(seed_chroma, 90.0))
    secondary_chroma = min(seed_chroma, 16.0)
    tertiary_chroma = min(seed_chroma, 24.0)
    neutral_chroma = min(seed_chroma, 4.0)
    neutral_variant_chroma = min(seed_chroma, 8.0)

    tertiary_hue = _shift_hue(seed_hue, 60.0)
    error_red = _hex_to_rgb("#B3261E")
    _, error_chroma, error_hue = _rgb_to_lch(error_red)
    error_chroma = max(50.0, min(error_chroma, 90.0))

    def primary(tone: float) -> str:
        return _tonal(tone, primary_chroma, seed_hue)

    def secondary(tone: float) -> str:
        return _tonal(tone, secondary_chroma, seed_hue)

    def tertiary(tone: float) -> str:
        return _tonal(tone, tertiary_chroma, tertiary_hue)

    def neutral(tone: float) -> str:
        return _tonal(tone, neutral_chroma, seed_hue)

    def variant(tone: float) -> str:
        return _tonal(tone, neutral_variant_chroma, seed_hue)

    def error(tone: float) -> str:
        return _tonal(tone, error_chroma, error_hue)

    if dark:
        roles = {
            "window": neutral(6),
            "panel": neutral(12),
            "panel_alt": neutral(17),
            "canvas_frame": neutral(10),
            "border": variant(30),
            "text": neutral(90),
            "muted": variant(80),
            "accent": primary(80),
            "accent_text": primary(20),
            "accent_soft": primary(30),
            "accent_soft_text": primary(90),
            "hover": neutral(22),
            "active": primary(30),
            "success": _tonal(80, 40.0, 145.0),
            "warning": _tonal(85, 55.0, 80.0),
            "danger": error(80),
        }
    else:
        roles = {
            "window": neutral(94),
            "panel": neutral(98),
            "panel_alt": neutral(96),
            "canvas_frame": neutral(92),
            "border": variant(80),
            "text": neutral(10),
            "muted": variant(30),
            "accent": primary(40),
            "accent_text": primary(100),
            "accent_soft": primary(90),
            "accent_soft_text": primary(10),
            "hover": neutral(92),
            "active": primary(90),
            "success": _tonal(40, 45.0, 145.0),
            "warning": _tonal(45, 60.0, 70.0),
            "danger": error(40),
        }

    # A readable "on" colour for the semantic roles. Computed from the role's
    # own lightness rather than assumed, because a light theme's warning is a
    # mid-tone that needs white on it while a dark theme's is nearly white and
    # needs black.
    for name in ("success", "warning", "danger"):
        roles[f"on_{name}"] = _on_colour(roles[name])
    roles["on_accent"] = roles["accent_text"]
    roles["disabled_bg"] = variant(90) if not dark else neutral(22)
    roles["disabled_text"] = variant(60) if not dark else variant(50)

    # Container colours, following Material's container / on-container pair: a
    # quiet surface tinted with the family's hue, carrying text in that family.
    #
    # A banner needs *three* roles, not one. Using the semantic colour itself as
    # the background fails at both ends of the range -- a dark theme's warning
    # is near-white, so a bar filled with it glares, while the light theme's is
    # a mid-tone that makes dark text unreadable. Naming the container here is
    # what stops each call site inventing its own cream bar, which is how seven
    # of them ended up frozen into a dark theme during this tool's own history.
    roles["success_container"] = _tonal(90 if not dark else 30, 30.0, 145.0)
    roles["on_success_container"] = _tonal(10 if not dark else 90, 40.0, 145.0)
    roles["warning_container"] = _tonal(92 if not dark else 30, 45.0, 75.0)
    roles["on_warning_container"] = _tonal(18 if not dark else 92, 55.0, 70.0)
    roles["danger_container"] = error(90) if not dark else error(30)
    roles["on_danger_container"] = error(10) if not dark else error(90)
    return roles


def _on_colour(background: str) -> str:
    """Black or white, whichever reads better on ``background``.

    Uses relative luminance with the WCAG contrast formula rather than a
    lightness threshold, because perceived lightness and numeric lightness
    disagree most in the yellows and cyans -- exactly where a warning colour
    lives.
    """
    r, g, b = _hex_to_rgb(background)
    luminance = 0.2126 * _linearise(r) + 0.7152 * _linearise(g) + 0.0722 * _linearise(b)
    white_contrast = 1.05 / (luminance + 0.05)
    black_contrast = (luminance + 0.05) / 0.05
    return "#000000" if black_contrast >= white_contrast else "#FFFFFF"


def scheme_from_seed(seed: str, dark: bool = False) -> Scheme:
    """The full scheme for a seed colour, by the Material 3 baseline."""
    # Normalise first so an invalid value fails here rather than deep inside
    # the tonal maths, and so the settings file always holds a canonical hex.
    clean = _rgb_to_hex(_hex_to_rgb(seed))
    return Scheme(seed=clean, dark=bool(dark), roles=_scheme_roles(clean, dark))


def scheme_from_roles(
    roles: dict[str, str], *, seed: str = DEFAULT_SEED, dark: bool = False
) -> Scheme:
    """A scheme whose roles were edited by hand.

    Missing roles fall back to the generated scheme rather than raising: the
    advanced editor only touches a few, and a saved file written by an older
    build will not have the ones added since.
    """
    base = scheme_from_seed(seed, dark)
    merged = dict(base.roles)
    changed = False
    for key, value in roles.items():
        # Only roles this build knows about. Keeping an unrecognised key would
        # put a value in the table that nothing reads and that the next save
        # would write back out -- a stale key surviving forever because a file
        # was once written by a different version.
        if key not in merged:
            continue
        try:
            colour = _rgb_to_hex(_hex_to_rgb(value))
        except ValueError:
            continue
        if merged[key] != colour:
            changed = True
        merged[key] = colour
    # ``custom`` records whether the result actually differs from the generated
    # scheme, rather than merely whether overrides were supplied. Passing the
    # generated colours back in is not a customisation, and flagging it as one
    # would make the settings panel say "custom" for an untouched theme.
    return Scheme(seed=base.seed, dark=dark, roles=merged, custom=changed)


# ------------------------------------------------------------------ storage


def settings_path() -> Path:
    """Where the interface preferences live.

    Follows the same split as :func:`pcbart.paths.cache_dir`: from source the
    file sits in ``out/`` with everything else the tool produces, and a packaged
    build keeps it in the per-user directory, which is writable without
    elevation and survives upgrades.

    ⚠️ **Not directly in the project root.** Writing ``settings.json`` beside
    the source put an untracked file in the repository during development --
    and worse, whatever the developer picked while testing then became the
    default for every screenshot and every test that did not pin the scheme.
    Named explicitly as ``settings.json`` rather than reusing ``data_root()``
    bare for that reason.
    """
    from .paths import data_root, is_frozen

    root = data_root()
    if not is_frozen():
        root = root / "out"
        root.mkdir(parents=True, exist_ok=True)
    return root / "settings.json"


def load_settings() -> dict:
    """The saved preferences, or an empty dict.

    Never raises. A preferences file that has been hand-edited into invalid
    JSON must not stop the program from starting -- the worst outcome of
    falling back to defaults is that the user re-picks a colour.
    """
    path = settings_path()
    try:
        with open(path, encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def save_settings(data: dict) -> bool:
    """Write the preferences. Returns whether it worked."""
    path = settings_path()
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(data, handle, ensure_ascii=False, indent=2)
    except OSError:
        return False
    return True


def scheme_from_settings(data: dict | None = None) -> Scheme:
    """The scheme the saved preferences describe."""
    data = load_settings() if data is None else data
    seed = data.get("seed") or DEFAULT_SEED
    dark = bool(data.get("dark", False))
    try:
        scheme = scheme_from_seed(seed, dark)
    except ValueError:
        return scheme_from_seed(DEFAULT_SEED, dark)
    custom = data.get("roles")
    if isinstance(custom, dict) and custom:
        return scheme_from_roles(custom, seed=scheme.seed, dark=dark)
    return scheme


def settings_for(scheme: Scheme) -> dict:
    """The preferences dict that reproduces this scheme."""
    return {
        "seed": scheme.seed,
        "dark": scheme.dark,
        # Only the overrides are stored, not all sixteen roles: a future build
        # that improves the generator should improve every preset, and storing
        # the whole table would freeze this build's maths into the file.
        "roles": dict(scheme.roles) if scheme.custom else {},
    }


def save_settings_keeping(data: dict | None = None, **updates) -> bool:
    """Merge ``updates`` (and ``data``, if given) into the saved preferences.

    ⚠️ ``save_settings`` **replaces** the whole file, and the file now holds
    more than the colour scheme (the external redraw-model path). Writing one
    of them with it would silently erase the other -- and the symptom would
    appear much later, as "the setting I picked does not stick". Every writer
    that owns only part of the file goes through here.

    A value of ``None`` removes its key rather than storing a null -- an absent
    key is what "not chosen yet" already means, and a stored ``null`` would
    read as a choice in the panel.
    """
    merged = load_settings()
    if data:
        merged.update(data)
    for key, value in updates.items():
        if value is None:
            merged.pop(key, None)
        else:
            merged[key] = value
    return save_settings(merged)
