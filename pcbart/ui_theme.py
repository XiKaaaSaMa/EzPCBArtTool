"""The interface's colour scheme, generated from one seed colour.

The user picks a colour; everything else follows. That is Material Design 3's
central idea and the reason this module exists instead of a table of hand-picked
hex values: an interface has about twenty distinct surface and accent roles, and
hand-picking twenty colours per preset is both tedious and how a palette ends up
with three near-identical greys that are subtly wrong.

**How the colours are derived.** The seed is converted to CIE LCh, and a *tonal
palette* is generated by holding the hue and sweeping lightness from 0 to 100.
Material's own generator does this in HCT; LCh is the same idea with standard
colour science instead of a bespoke space, and it needs no dependency. Chroma is
reduced per tone until the colour fits in sRGB, which is what keeps a tone from
clipping to a flat primary when it gets very light or very dark.

Roles are then read off the palette at the tones Material specifies -- primary
is tone 40 in the light scheme and tone 80 in the dark one, surfaces are
low-chroma neutrals, and so on. The numbers below are from the Material 3
baseline scheme, so a seed produces the scheme Material would have produced.

**Chroma budgets.** Material does not use the seed's full chroma for everything.
Neutrals get a trace of the hue so the greys feel related rather than dead, and
the secondary/tertiary families are deliberately quieter than the primary.
Those caps are the difference between a palette that looks designed and one
where every surface is shouting.

Not themed here: the **canvas**. It stays black, because that was a separate
and explicit decision -- the layer colours come from EasyEDA's own table and are
chosen to read on a dark board view. The panels follow the user's theme.
"""

