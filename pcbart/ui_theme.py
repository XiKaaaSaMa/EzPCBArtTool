# --------------------------------------------------------------- colour maths


def _hex_to_rgb(value: str) -> tuple[float, float, float]:
    text = value.strip().lstrip("#")
    if len(text) == 3:
        text = "".join(c * 2 for c in text)
    if len(text) != 6:
        raise ValueError(f"不是有效的颜色: {value!r}")
    try:
        number = int(text, 16)
    except ValueError:
        raise ValueError(f"不是有效的颜色: {value!r}") from None
    return (
        ((number >> 16) & 0xFF) / 255.0,
        ((number >> 8) & 0xFF) / 255.0,
        (number & 0xFF) / 255.0,
    )


def _rgb_to_hex(rgb: tuple[float, float, float]) -> str:
    return "#" + "".join(
        f"{max(0, min(255, round(c * 255))):02X}" for c in rgb
    )


def _linearise(channel: float) -> float:
    return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4


def _delinearise(channel: float) -> float:
    return channel * 12.92 if channel <= 0.0031308 else 1.055 * channel ** (1 / 2.4) - 0.055


#: sRGB primaries against D65, the matrix the CSS spec publishes.
_TO_XYZ = (
    (0.4123908, 0.3575843, 0.1804808),
    (0.2126390, 0.7151687, 0.0721923),
    (0.0193308, 0.1191948, 0.9505322),
)
_FROM_XYZ = (
    (3.2409699, -1.5373832, -0.4986108),
    (-0.9692436, 1.8759675, 0.0415551),
    (0.0556301, -0.2039770, 1.0569715),
)
_WHITE = (0.9504559, 1.0000000, 1.0890578)


def _rgb_to_lch(rgb: tuple[float, float, float]) -> tuple[float, float, float]:
    """sRGB to CIE LCh(ab). Lightness 0..100, chroma unbounded, hue degrees."""
    linear = tuple(_linearise(c) for c in rgb)
    xyz = tuple(sum(row[i] * linear[i] for i in range(3)) for row in _TO_XYZ)
    x, y, z = (
        xyz[0] / _WHITE[0],
        xyz[1] / _WHITE[1],
        xyz[2] / _WHITE[2],
    )

    def f(t: float) -> float:
        return t ** (1 / 3) if t > (6 / 29) ** 3 else t / (3 * (6 / 29) ** 2) + 4 / 29

    fx, fy, fz = f(x), f(y), f(z)
    lightness = 116 * fy - 16
    a = 500 * (fx - fy)
    b = 200 * (fy - fz)
    chroma = math.hypot(a, b)
    hue = math.degrees(math.atan2(b, a)) % 360
    return lightness, chroma, hue


def _lch_to_rgb(lightness: float, chroma: float, hue: float) -> tuple[float, float, float]:
    """CIE LCh(ab) back to sRGB, **without** clamping, so callers can test gamut."""
    radians = math.radians(hue)
    a = chroma * math.cos(radians)
    b = chroma * math.sin(radians)

    fy = (lightness + 16) / 116
    fx = fy + a / 500
    fz = fy - b / 200

    def finv(t: float) -> float:
        return t ** 3 if t ** 3 > (6 / 29) ** 3 else 3 * (6 / 29) ** 2 * (t - 4 / 29)

    xyz = (
        finv(fx) * _WHITE[0],
        finv(fy) * _WHITE[1],
        finv(fz) * _WHITE[2],
    )
    linear = tuple(sum(row[i] * xyz[i] for i in range(3)) for row in _FROM_XYZ)
    return tuple(_delinearise(max(0.0, c)) for c in linear)


def _in_gamut(rgb: tuple[float, float, float], tolerance: float = 1e-4) -> bool:
    return all(-tolerance <= c <= 1 + tolerance for c in rgb)


def _tonal(lightness: float, chroma: float, hue: float) -> str:
    """One tone: the requested lightness, the most chroma sRGB can hold.

    Reducing chroma rather than clamping the channels is what keeps a light
    tone *pale* instead of washing it out to grey or clipping it to a saturated
    sliver. A binary search is used because the gamut boundary is not a simple
    function of chroma.
    """
    if lightness <= 0:
        return "#000000"
    if lightness >= 100:
        return "#FFFFFF"

    low, high = 0.0, max(0.0, chroma)
    best = _lch_to_rgb(lightness, 0.0, hue)
    if _in_gamut(_lch_to_rgb(lightness, high, hue)):
        best = _lch_to_rgb(lightness, high, hue)
    else:
        for _ in range(24):
            middle = (low + high) / 2
            candidate = _lch_to_rgb(lightness, middle, hue)
            if _in_gamut(candidate):
                low = middle
                best = candidate
            else:
                high = middle
    return _rgb_to_hex(tuple(max(0.0, min(1.0, c)) for c in best))


def _shift_hue(hue: float, degrees: float) -> float:
    return (hue + degrees) % 360


# ------------------------------------------------------------------- scheme


@dataclass(frozen=True)
class Scheme:
    """Every colour the interface uses, resolved for one mode."""

    seed: str
    dark: bool
    roles: dict[str, str] = field(default_factory=dict)
    custom: bool = False
    """True when any role was overridden by hand in the advanced editor.

    Kept so the settings panel can say so, and so re-picking a preset knows to
    discard the overrides rather than silently keeping a mixture.
    """

    def __getitem__(self, key: str) -> str:
        return self.roles[key]

    def get(self, key: str, default: str = "#000000") -> str:
        return self.roles.get(key, default)


